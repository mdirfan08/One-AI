import { useState } from "react";
import { api } from "../api";
import type { Provider } from "../types";
import { Banner, Card } from "../ui";

const EXAMPLE = "Create a responsive website for a startup, generate a logo, write website content, create a promotional video workflow and prepare a pitch presentation.";

function toBase64(file: File): Promise<string> {
  return new Promise((res, rej) => {
    const r = new FileReader();
    r.onload = () => res(String(r.result).split(",")[1] ?? "");
    r.onerror = () => rej(new Error("Could not read file"));
    r.readAsDataURL(file);
  });
}

export default function TaskComposer({ providers, onCreated }: { providers: Provider[]; onCreated: (id: string) => void }) {
  const [request, setRequest] = useState("");
  const [mode, setMode] = useState<"demo" | "integration">("demo");
  const [execution, setExecution] = useState<"manual" | "auto">("manual");
  const [constraints, setConstraints] = useState("");
  const [formats, setFormats] = useState("");
  const [maxUsd, setMaxUsd] = useState("");
  const [maxTasks, setMaxTasks] = useState("12");
  const [maxRetries, setMaxRetries] = useState("2");
  const [planner, setPlanner] = useState("");
  const [inject, setInject] = useState(false);
  const [files, setFiles] = useState<File[]>([]);
  const [busy, setBusy] = useState("");
  const [error, setError] = useState("");
  const real = providers.filter((p) => p.id !== "demo");
  const configured = real.filter((p) => p.configured);

  async function submit() {
    setError("");
    try {
      setBusy("Creating project...");
      const p = await api.createProject({
        request, mode, execution, constraints, output_formats: formats.split(",").map((s) => s.trim()).filter(Boolean),
        planner_provider: planner || null, demo_options: { inject_failure: inject },
        limits: { max_usd: maxUsd ? Number(maxUsd) : null, max_tasks: Number(maxTasks), max_retries: Number(maxRetries) },
      });
      for (const f of files) { setBusy(`Uploading ${f.name}...`); await api.upload(p.id, f.name, await toBase64(f)); }
      setBusy("Planning (this may take a moment)...");
      try { await api.plan(p.id); } catch (e) { setError(`Project saved, but planning failed: ${(e as Error).message}`); }
      onCreated(p.id);
    } catch (e) { setError((e as Error).message); } finally { setBusy(""); }
  }

  return (
    <Card title="What do you want to accomplish?">
      <textarea className="big" value={request} onChange={(e) => setRequest(e.target.value)} rows={5}
        placeholder="Describe any task in plain language: build a site, write copy, design a logo, plan a video, make a deck, research a topic..." />
      <div className="row wrap">
        <button className="btn link" onClick={() => setRequest(EXAMPLE)}>Use an example</button>
        <label className="btn sm file">Attach text files<input type="file" multiple hidden accept=".txt,.md,.csv,.json,.html,.css,.js,.ts,.tsx,.py,.yml,.yaml"
          onChange={(e) => setFiles([...files, ...Array.from(e.target.files ?? [])].slice(0, 10))} /></label>
        {files.map((f) => <span key={f.name} className="chip">{f.name}<button aria-label={`Remove ${f.name}`} onClick={() => setFiles(files.filter((x) => x !== f))}>×</button></span>)}
      </div>

      <div className="grid2">
        <div>
          <label>Mode</label>
          <div className="seg">
            <button className={mode === "demo" ? "on" : ""} onClick={() => setMode("demo")}>Demo (free, simulated)</button>
            <button className={mode === "integration" ? "on" : ""} onClick={() => setMode("integration")}>Integration (your API keys)</button>
          </div>
        </div>
        <div>
          <label>Execution</label>
          <div className="seg">
            <button className={execution === "manual" ? "on" : ""} onClick={() => setExecution("manual")}>Review plan &amp; approve steps</button>
            <button className={execution === "auto" ? "on" : ""} onClick={() => setExecution("auto")}>Automatic</button>
          </div>
        </div>
      </div>

      {mode === "demo" ? (
        <Banner>Demo mode makes <b>no external AI calls</b>. All output is generated by a deterministic simulator and is labelled <b>SIMULATED</b>.</Banner>
      ) : configured.length === 0 ? (
        <Banner kind="warn">No provider credentials are configured yet. Add an API key under <b>Providers</b> (or set it in the backend environment), otherwise planning will fail.</Banner>
      ) : (
        <Banner kind="warn">Integration mode calls provider APIs ({configured.map((p) => p.display_name).join(", ")}). <b>This may charge your provider account.</b> Set a spending/token limit below. A ChatGPT/Claude/Gemini app subscription does not include API access.</Banner>
      )}

      <details>
        <summary>Constraints, formats and limits</summary>
        <label>Constraints / preferences</label>
        <textarea value={constraints} onChange={(e) => setConstraints(e.target.value)} rows={2} placeholder="e.g. Use TypeScript and Vite. Brand colours: teal and white. Formal tone." />
        <div className="grid2">
          <div><label>Output formats (comma-separated)</label><input value={formats} onChange={(e) => setFormats(e.target.value)} placeholder="pptx, docx, html" /></div>
          <div><label>Planner provider</label>
            <select value={planner} onChange={(e) => setPlanner(e.target.value)}>
              <option value="">Automatic</option>
              {providers.filter((p) => (mode === "demo" ? p.id === "demo" : p.id !== "demo")).map((p) => <option key={p.id} value={p.id}>{p.display_name}</option>)}
            </select></div>
        </div>
        <div className="grid3">
          <div><label>Spending limit (USD)</label><input type="number" min="0" step="0.01" value={maxUsd} onChange={(e) => setMaxUsd(e.target.value)} placeholder="none" /></div>
          <div><label>Max tasks</label><input type="number" min="1" max="30" value={maxTasks} onChange={(e) => setMaxTasks(e.target.value)} /></div>
          <div><label>Max retries / task</label><input type="number" min="0" max="5" value={maxRetries} onChange={(e) => setMaxRetries(e.target.value)} /></div>
        </div>
        <p className="muted small">A USD limit only works for models with a price in your pricing file (the app refuses calls whose price is unknown). Token and call limits always apply. Limits are hard stops.</p>
        {mode === "demo" && <label className="check"><input type="checkbox" checked={inject} onChange={(e) => setInject(e.target.checked)} /> Simulate a transient provider failure (shows retries)</label>}
      </details>

      {error && <Banner kind="error">{error}</Banner>}
      <div className="row end">
        <button className="btn primary" disabled={!request.trim() || !!busy} onClick={submit}>{busy || "Create plan"}</button>
      </div>
    </Card>
  );
}
