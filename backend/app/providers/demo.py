"""Demo provider: deterministic, offline, free. EVERYTHING it produces is labelled SIMULATED
and every result carries simulated=True so the UI/exports can never present it as real AI output."""
from __future__ import annotations

import json
import re

from .base import GenerationRequest, GenerationResult, ImageResult, ProviderAdapter, ProviderError, ProviderStatus
from ..core.capabilities import TEXT, JSON, CODE, IMAGE_GEN
from ..core.pricing import estimate_tokens

BANNER = "SIMULATED OUTPUT: generated by the built-in demo provider, not by a real AI model."


def _flags(request: str) -> dict:
    r = request.lower()
    has = lambda *words: any(w in r for w in words)
    return {
        "web": has("website", "web app", "webapp", "landing page", "web site", "frontend", "react", "html"),
        "code": has("code", "app", "software", "debug", "api", "script", "program"),
        "image": has("logo", "image", "illustration", "poster", "banner", "visual", "icon"),
        "video": has("video", "promo", "commercial", "reel"),
        "deck": has("presentation", "pitch", "slides", "deck", "powerpoint"),
        "social": has("social", "instagram", "twitter", "linkedin", "tweet"),
        "doc": has("document", "report", "whitepaper", "proposal", "memo"),
        "write": has("content", "copy", "blog", "article", "write", "marketing"),
        "research": has("research", "analy", "market", "competitor", "study"),
    }


def demo_plan(request: str, max_tasks: int = 12) -> dict:
    f = _flags(request)
    tasks = []

    def add(id_, title, kind, desc, deps, criteria, outputs=None):
        tasks.append({"id": id_, "title": title, "kind": kind, "description": desc, "depends_on": deps,
                      "inputs": ["User request"] + [f"Output of {d}" for d in deps],
                      "expected_outputs": outputs or [], "acceptance_criteria": criteria})

    multi = sum(1 for k in ("web", "image", "video", "deck", "social", "doc") if f[k]) >= 2
    if f["research"] or multi:
        add("research", "Background research", "research", "Gather background, audience and positioning notes relevant to the request.",
            [], ["Covers audience and positioning", "Flags uncertain claims explicitly"])
    base = ["research"] if tasks else []
    if f["write"] or f["web"] or f["social"] or multi:
        add("copy", "Write core messaging and copy", "writing", "Write headline, value proposition and section copy.",
            base, ["Includes headline and value proposition", "Consistent tone"])
    copy_dep = ["copy"] if any(t["id"] == "copy" for t in tasks) else base
    if f["image"]:
        add("logo", "Generate visual identity image", "image", "Create the requested image/logo concept.", base,
            ["Image artifact produced"], [{"name": "logo", "type": "image"}])
    if f["web"] or f["code"]:
        add("spec", "Technical specification", "code_spec", "Define pages, components, file tree and implementation plan.",
            copy_dep, ["Lists files to create", "Defines acceptance tests"])
        add("site", "Implement the web project", "code_files", "Generate the project files in the controlled workspace.",
            ["spec"] + copy_dep, ["At least one runnable file produced", "Uses the supplied copy"], [{"name": "project", "type": "code_bundle"}])
    if f["video"]:
        add("video_script", "Video script", "video_script", "Write the promo video script.", copy_dep or base, ["Has scenes and narration"])
        add("storyboard", "Video storyboard", "video_storyboard", "Create a shot-by-shot storyboard.", ["video_script"], ["Every scene has a visual description"])
        add("video_assets", "Generate video footage and assets", "video_assets", "Produce clips/footage for the storyboard.", ["storyboard"],
            ["Footage supplied"], [{"name": "footage", "type": "video"}])
        add("assembly", "Video assembly plan", "video_assembly", "Describe how to edit assets into the final video.", ["storyboard"], ["Lists editing steps"])
    if f["deck"]:
        add("deck", "Presentation", "presentation", "Create a slide outline and export it to .pptx.", copy_dep or base,
            ["6-10 slides", "Each slide has a title and bullets"], [{"name": "deck", "type": "pptx"}])
    if f["social"]:
        add("social", "Social media posts", "social", "Draft platform-specific posts.", copy_dep or base, ["At least 3 posts"])
    if f["doc"]:
        add("doc", "Document", "document", "Write the requested structured document.", base, ["Has sections and a summary"],
            [{"name": "document", "type": "docx"}])
    if not tasks:
        add("answer", "Complete the request", "general", "Respond to the request directly.", [], ["Directly addresses the request"])
    tasks = tasks[:max_tasks]
    ids = {t["id"] for t in tasks}
    for t in tasks:
        t["depends_on"] = [d for d in t["depends_on"] if d in ids]
    return {
        "objective": request.strip()[:300] or "Complete the user's request",
        "requirements": ["Follow the user's request and constraints", BANNER],
        "assumptions": ["Demo mode: a deterministic heuristic planner was used (no AI call).",
                        "Reasonable defaults were chosen where the request was silent."],
        "clarifying_questions": [],
        "deliverables": [f"{t['title']} ({t['kind']})" for t in tasks],
        "tasks": tasks,
    }


def _site_files(title: str, request: str) -> str:
    t = re.sub(r"[<>&\"']", "", title)[:80] or "Demo Project"
    html = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{t} (SIMULATED)</title><link rel="stylesheet" href="styles.css"></head>
<body><div class="banner">SIMULATED OUTPUT: demo provider placeholder site</div>
<header><h1>{t}</h1><p>Placeholder landing page generated by the demo provider.</p><button id="cta">Get started</button></header>
<main><section><h2>Features</h2><ul><li>Fast</li><li>Responsive</li><li>Simple</li></ul></section></main>
<script src="script.js"></script></body></html>"""
    css = "body{font-family:system-ui,sans-serif;margin:0}.banner{background:#b45309;color:#fff;padding:8px;text-align:center}header{padding:48px 24px;text-align:center}button{padding:10px 18px;border-radius:8px;border:0;background:#4f46e5;color:#fff}main{max-width:720px;margin:auto;padding:24px}"
    js = "document.getElementById('cta').addEventListener('click',()=>alert('Simulated demo site'));"
    return (f"=== FILE: index.html ===\n{html}\n=== END FILE ===\n"
            f"=== FILE: styles.css ===\n{css}\n=== END FILE ===\n"
            f"=== FILE: script.js ===\n{js}\n=== END FILE ===\n")


def _deck(title: str) -> str:
    slides = [{"title": f"[SIMULATED] {title}", "bullets": ["Demo provider output", "Replace with real content"], "notes": BANNER}]
    for name in ("Problem", "Solution", "Market", "Product", "Roadmap", "Ask"):
        slides.append({"title": name, "bullets": [f"Placeholder point about {name.lower()}", "Second placeholder point"], "notes": BANNER})
    return json.dumps({"title": f"[SIMULATED] {title}", "slides": slides})


class DemoProvider(ProviderAdapter):
    id = "demo"
    display_name = "Demo (simulated)"
    base_capabilities = frozenset({TEXT, JSON, CODE, IMAGE_GEN})
    default_model = "demo-simulator"
    may_charge = False

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.connection = "simulated"

    def is_configured(self) -> bool:
        return True

    def _build_client(self, api_key):  # pragma: no cover - unused
        return None

    def _list_models(self) -> list:
        return [self.default_model]

    def _generate_text(self, req: GenerationRequest) -> GenerationResult:
        md = req.metadata or {}
        kind = md.get("task_kind", "general")
        if md.get("inject_failure") and md.get("attempt", 1) == 1:
            raise ProviderError("Simulated transient provider failure (demo failure injection).", "unavailable", True, self.id)
        title = md.get("task_title", "Demo task")
        if kind == "planning":
            text = json.dumps(demo_plan(md.get("user_request", ""), md.get("max_tasks", 12)))
        elif kind == "evaluation":
            text = json.dumps({"passed": True, "criteria": [], "note": "simulated judge: always passes"})
        elif kind == "code_files":
            text = _site_files(title, md.get("user_request", ""))
        elif kind == "presentation":
            text = _deck(title)
        else:
            text = (f"> **{BANNER}**\n\n# {title}\n\n"
                    f"This is deterministic placeholder content for a `{kind}` task.\n\n"
                    f"- Original request (excerpt): {md.get('user_request', '')[:160]}\n"
                    "- Section 1: placeholder\n- Section 2: placeholder\n- Summary: placeholder\n")
        return GenerationResult(text=text, provider=self.id, model=self.model, simulated=True,
                                input_tokens=estimate_tokens(req.prompt), output_tokens=estimate_tokens(text))

    def _generate_image(self, prompt: str, size: str) -> ImageResult:
        svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">'
               '<rect width="512" height="512" fill="#e0e7ff"/><circle cx="256" cy="230" r="110" fill="#6366f1"/>'
               '<text x="256" y="470" font-family="sans-serif" font-size="22" text-anchor="middle" fill="#92400e">'
               'SIMULATED PLACEHOLDER (not AI-generated)</text></svg>')
        return ImageResult(data=svg.encode(), mime="image/svg+xml", provider=self.id, model=self.model, simulated=True,
                           note="Placeholder SVG from the demo provider.")

    def status(self) -> ProviderStatus:
        s = super().status()
        s.configured, s.connection, s.credential_source = True, "simulated", None
        s.quota_info = "N/A: simulated provider, free, no external calls."
        s.notes = ["All output is simulated and labelled as such.", "No video/voice generation (those use manual handoff)."]
        return s
